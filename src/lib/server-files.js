/** sitemap.xml, robots.txt and the Apache .htaccess (HTTPS, redirects, 404, caching). */

const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function sitemap(site, pages) {
  const rows = pages
    .map(
      (p) =>
        `  <url>\n    <loc>${xml(site.url + p.url)}</loc>${p.data.updated ? `\n    <lastmod>${p.data.updated}</lastmod>` : ''}\n  </url>`,
    )
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${rows}\n</urlset>\n`;
}

export function robots(site, { preview }) {
  if (preview) return 'User-agent: *\nDisallow: /\n';
  return `User-agent: *\nAllow: /\n\nSitemap: ${site.url}/sitemap.xml\n`;
}

export function htaccess(site, redirects) {
  const host = new URL(site.url).host;
  const hostRe = host.replace(/\./g, '\\.');
  const rules = redirects
    .map((r) => `RewriteRule ^${r.from.replace(/^\//, '').replace(/\/$/, '').replace(/[.+*?()[\]{}|^$]/g, '\\$&')}/?$ ${r.to} [R=301,L]`)
    .join('\n');

  return `# Generated by the site build. Do not edit by hand: change redirects.json and rebuild.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On

# One canonical host: https + no www
RewriteCond %{HTTPS} off
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTP_HOST} ^www\\.${hostRe}$ [NC]
RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]

# Permanent redirects (from redirects.json)
${rules || '# (none)'}
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json application/xml image/svg+xml
</IfModule>

<IfModule mod_mime.c>
AddType font/woff2 .woff2
AddType image/avif .avif
AddType image/webp .webp
</IfModule>

<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType text/html "access plus 0 seconds"
ExpiresByType font/woff2 "access plus 1 year"
ExpiresByType image/avif "access plus 30 days"
ExpiresByType image/webp "access plus 30 days"
ExpiresByType image/jpeg "access plus 30 days"
ExpiresByType image/png "access plus 30 days"
</IfModule>

<IfModule mod_headers.c>
Header set X-Content-Type-Options "nosniff"
Header set Referrer-Policy "strict-origin-when-cross-origin"
# File names under /assets/ contain a content hash, so they can be cached for a year
<FilesMatch "\\.[0-9a-f]{8,}\\.(css|js)$">
Header set Cache-Control "public, max-age=31536000, immutable"
</FilesMatch>
<FilesMatch "\\.html$">
Header set Cache-Control "no-cache"
</FilesMatch>
</IfModule>
`;
}
